#!/bin/bash
# ============================================================
#  kexvim installer (minimal) - 2026-09-09
#  This script does ONLY:
#    1. ensure Node.js >=22.5 (the sole dependency installed here)
#    2. download kexvim.js (skip when present)
#    3. launch the installer process: node kexvim.js bootstrap
#       (deps + example configs + init + start)
#  With arguments it forwards them to kexvim.js directly.
# ============================================================
set -u
DIR="${KEXVIM_HOME:-$HOME/.kexvim}"
REPO="${KEXVIM_REPO:-https://gitee.com/moscowzk/kexvim}"
NODEVER=v22.18.0

download_node() {
    local NODE_OS NODE_ARCH EXT
    case "$(uname -s)" in Darwin) NODE_OS=darwin ;; *) NODE_OS=linux ;; esac
    case "$(uname -m)" in arm64|aarch64) NODE_ARCH=arm64 ;; *) NODE_ARCH=x64 ;; esac
    EXT=tar.gz
    echo "[~] Downloading Node.js $NODEVER ($NODE_OS-$NODE_ARCH)..."
    curl -fsSL "https://nodejs.org/dist/$NODEVER/node-$NODEVER-$NODE_OS-$NODE_ARCH.$EXT" -o "$DIR/node.$EXT" || { echo "[X] Node download failed"; exit 1; }
    rm -rf "$DIR/node"
    tar -xzf "$DIR/node.$EXT" -C "$DIR" && mv "$DIR/node-$NODEVER-$NODE_OS-$NODE_ARCH" "$DIR/node"
    rm -f "$DIR/node.$EXT"
}

mkdir -p "$DIR"

# -- 1. Node.js >=22.5 (node:sqlite); portable copy auto-downloaded when missing/too old
NODEEXE=""
[ -x "$DIR/node/bin/node" ] && NODEEXE="$DIR/node/bin/node"
[ -z "$NODEEXE" ] && command -v node >/dev/null 2>&1 && NODEEXE="$(command -v node)"
if [ -z "$NODEEXE" ] || ! "$NODEEXE" -e "const v=process.versions.node.split('.').map(Number);process.exit(v[0]>22||(v[0]===22&&v[1]>=5)?0:1)" 2>/dev/null; then
    [ -n "$NODEEXE" ] && echo "[~] Node too old ($("$NODEEXE" -v)), re-downloading $NODEVER..."
    download_node
    NODEEXE="$DIR/node/bin/node"
fi

# -- 2. kexvim code (skip download when present)
if [ ! -f "$DIR/kexvim.js" ]; then
    echo "[~] Downloading kexvim.js..."
    curl -fsSL "$REPO/raw/main/kexvim.js" -o "$DIR/kexvim.js" || { echo "[X] kexvim.js download failed"; exit 1; }
fi

cd "$DIR" || exit 1

# -- 3. global `kexvim` command: launcher + PATH (idempotent; install path only)
install_command() {
    local launcher="$DIR/kexvim" bindir="" rc found=0
    # launcher is regenerated on every install so it always tracks $DIR / portable Node
    cat > "$launcher" <<LAUNCHER
#!/bin/sh
# kexvim launcher - generated by kexvim-install.sh (safe to regenerate)
KEXVIM_HOME="$DIR"
NODE="\$KEXVIM_HOME/node/bin/node"
[ -x "\$NODE" ] || NODE=node
exec "\$NODE" "\$KEXVIM_HOME/kexvim.js" "\$@"
LAUNCHER
    chmod 755 "$launcher" 2>/dev/null

    if [ -n "${KEXVIM_BIN_DIR:-}" ]; then
        bindir="$KEXVIM_BIN_DIR"
        mkdir -p "$bindir" 2>/dev/null
    elif [ -w /usr/local/bin ]; then
        bindir=/usr/local/bin
    else
        bindir="$HOME/.local/bin"
        mkdir -p "$bindir" 2>/dev/null
    fi

    if ! ln -sf "$launcher" "$bindir/kexvim" 2>/dev/null; then
        echo "[!] could not register the 'kexvim' command; run manually:"
        echo "    ln -s \"$launcher\" /usr/local/bin/kexvim"
        return
    fi
    echo "[+] kexvim command: $bindir/kexvim"

    # PATH: append once (idempotent) when bindir is not on PATH yet
    case ":$PATH:" in
        *":$bindir:"*) return ;;
    esac
    for rc in "$HOME/.zshrc" "$HOME/.zprofile" "$HOME/.bashrc" "$HOME/.profile"; do
        [ -f "$rc" ] || continue
        found=1
        grep -qs "kexvim-install: PATH" "$rc" && continue
        printf '\n# kexvim-install: PATH\nexport PATH="%s:$PATH"\n' "$bindir" >> "$rc"
        echo "[+] PATH updated in $rc"
    done
    if [ "$found" = 0 ]; then
        # macOS zsh reads ~/.zprofile (not ~/.profile) - cover both when no rc exists yet
        printf '# kexvim-install: PATH\nexport PATH="%s:$PATH"\n' "$bindir" >> "$HOME/.profile"
        echo "[+] PATH updated in $HOME/.profile"
        if [ "$(uname -s)" = Darwin ]; then
            printf '# kexvim-install: PATH\nexport PATH="%s:$PATH"\n' "$bindir" >> "$HOME/.zprofile"
            echo "[+] PATH updated in $HOME/.zprofile"
        fi
    fi
    echo "[!] open a new terminal to use 'kexvim'"
}

if [ $# -eq 0 ]; then
    install_command
fi

# -- 4. run: args passthrough; no args -> installer process
if [ $# -gt 0 ]; then
    exec "$NODEEXE" "$DIR/kexvim.js" "$@"
fi
"$NODEEXE" "$DIR/kexvim.js" bootstrap
RC=$?
# keep the window readable when launched from a double-click
if [ -t 0 ]; then
    echo
    read -r -p "Press Enter to close..." _
fi
exit $RC
